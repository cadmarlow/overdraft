import fs from 'node:fs';
import { BLOCKS, CUT_Z, streetZ, getIslandBoundsAtZ } from '../../js/city-config.js';
import { GEO } from '../../js/nyc-geodata.js';
import { sampleShore } from '../../js/highway-shore.js';
import { routeHighway } from './routing.mjs';
import { cscl, segLines, toWorld } from '../geo-base.mjs';

// The data loader also runs in a browser; only this offline invocation adapts file: requests.
const nativeFetch = globalThis.fetch;
globalThis.fetch = async url => new Response(fs.readFileSync(new URL(url)));
const { REAL_BUILDINGS } = await import('../../js/building-geodata.js');
globalThis.fetch = nativeFetch;
const smooth = (a, b, z) => { const t = Math.max(0, Math.min(1, (z - a) / (b - a))); return t * t * (3 - 2 * t); };
const shoreX = (z, west) => getIslandBoundsAtZ(z)[west ? 'westX' : 'eastX'];
const blockSidewalks = BLOCKS.filter(b => !(b.park > 0.6 && !b.median && b.parkName !== 'Bryant Park')).flatMap(b => b.rect ?
  [{ cx: b.cx, cz: b.cz, w: b.maxX - b.minX, d: b.maxZ - b.minZ }] :
  b.rects.map(([x0, x1, z0, z1]) => ({ cx: (x0 + x1) / 2, cz: (z0 + z1) / 2, w: x1 - x0 + 8.8, d: z1 - z0 + 8.8 })));
const park = GEO.parks.find(p => p.name === 'John V. Lindsay East River Park');
const zs = park.rings.flatMap(r => r.filter((_, i) => i % 2));
const er0 = Math.min(...zs), er1 = Math.max(...zs);
// CSCL level 17 is retained here: the old map export only retained level 13 and lost this FDR alignment.
const surveyed = cscl.filter(s => s.full_street_name === 'FRANKLIN D ROOSEVELT DR' && ['2', '3'].includes(s.rw_type))
  .flatMap(s => segLines(s).flatMap(line => { const p = line.map(v => toWorld(...v)); return p.slice(1).map((b, i) => [p[i], b]); }));
const routes = [];
for (const west of [true, false]) {
  const rows = sampleShore(west, CUT_Z + 40, west ? 6000 : 6330, z => west ? smooth(streetZ(66), streetZ(59) + 60, z) :
    Math.max(smooth(er0 - 60, er0, z) * (1 - smooth(er1 - 50, er1, z)),
      smooth(streetZ(90) - 40, streetZ(90), z) * (1 - smooth(streetZ(84), streetZ(84) + 40, z))), { blockSidewalks, shoreX });
  for (const r of rows) {
    r.preferred = r.s + r.sgn * (r.d0 + 7.6 * r.k);
    if (!west && r.z > 450 && r.z < 1800) {
      const xs = surveyed.filter(([a, b]) => r.z >= Math.min(a[1], b[1]) && r.z < Math.max(a[1], b[1]))
        .map(([a, b]) => a[0] + (b[0] - a[0]) * (r.z - a[1]) / (b[1] - a[1]));
      if (xs.length) {
        const w = smooth(450, 600, r.z) * (1 - smooth(1650, 1800, r.z));
        r.preferred += ((Math.min(...xs) + Math.max(...xs)) / 2 - r.preferred) * w;
      }
    }
  }
  let path;
  for (let iteration = 0; iteration < 8; iteration++) {
    path = routeHighway(rows, REAL_BUILDINGS, getIslandBoundsAtZ);
    let growth = 0;
    for (let i = 0; i < path.length; i++) {
      const a = path[Math.max(0, i - 1)], b = path[Math.min(path.length - 1, i + 1)];
      const reserve = !west && path[i].z > 4250 ? 9 : 9 * Math.hypot(1, (b.x - a.x) / (b.z - a.z));
      growth = Math.max(growth, reserve - (rows[i].reserve ?? 9));
      rows[i].reserve = Math.max(rows[i].reserve ?? 9, reserve);
    }
    console.log('width', west, iteration, growth.toFixed(3));
    if (growth < 0.015) break;
    if (iteration === 7) throw new Error('Highway width did not converge; no geometry was written');
  }
  routes.push({ west, z0: path[0].z, step: 3, x: path.map(p => Math.round(p.x * 1000) / 1000) });
  console.log(`${west ? 'West' : 'East'}: ${path.length} continuous road sections`);
}
fs.writeFileSync(new URL('../../js/highway-geodata.js', import.meta.url),
  '// Generated by tools/highways/build.mjs. Shared road, markings, barriers, ground and traffic corridor.\n' +
  `export const HIGHWAY_ROUTES = ${JSON.stringify(routes)};\n`);
