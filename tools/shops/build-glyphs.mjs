// Build assets/shops/glyphs.png and js/storefront-glyphs.js: the signed-distance glyph atlas of the shop signs.
// Needs the fonts (node tools/shops/fetch-fonts.mjs) and the dev server (npm run dev).
// Usage: node tools/shops/build-glyphs.mjs [http://localhost:5173]
import fs from 'node:fs';
import { runPage } from './headless.mjs';

const origin = process.argv[2] || 'http://localhost:5173';
const result = await runPage(`${origin}/tools/shops/glyphs.html`, { timeout: 900000 });
if (result.error) throw new Error(result.error);
const { png, metrics } = result;
fs.mkdirSync(new URL('../../assets/shops/', import.meta.url), { recursive: true });
fs.writeFileSync(new URL('../../assets/shops/glyphs.png', import.meta.url), Buffer.from(png.split(',')[1], 'base64'));
const header = '// Generated by tools/shops/build-glyphs.mjs; do not edit.\n' +
  '// Metrics of assets/shops/glyphs.png: three typefaces per RGB texel (group, channel), one cell per character, sizes and\n' +
  '// offsets in atlas pixels, advances and heights in ems. Typefaces: Google Fonts, SIL Open Font License (Permanent\n' +
  '// Marker: Apache 2.0).\n';
fs.writeFileSync(new URL('../../js/storefront-glyphs.js', import.meta.url),
  header + `const GLYPHS = ${JSON.stringify(metrics)};\n\nexport { GLYPHS };\n`);
console.log('glyphs.png', fs.statSync(new URL('../../assets/shops/glyphs.png', import.meta.url)).size, 'bytes');
